function system_guide_render_page(array $user): void
{
    $guide = system_guide_data();
    $chapters = system_guide_visible_tree($user);
    $role = system_guide_role_label((string) ($user['role'] ?? ''));

    echo '<section class="course-hero guide-hero" id="top">';
    echo '<div class="course-hero__content"><p class="eyebrow">Инструкция · ' . system_guide_e($role) . '</p>';
    echo '<h2>' . system_guide_e((string) $guide['title']) . '</h2>';
    echo '<p>' . system_guide_e((string) $guide['intro']) . '</p>';
    echo '<div class="course-hero__actions"><a class="primary" href="#guide-' . system_guide_e((string) ($chapters[0]['id'] ?? 'start')) . '">Начать чтение</a>';
    echo '<a class="ghost" href="' . e(app_path('/knowledge')) . '">Назад к обучению</a></div></div></section>';

    echo '<section class="course-overview" aria-label="Разделы инструкции">';
    foreach ($chapters as $chapter) {
        echo '<a class="course-overview__item" href="#guide-' . system_guide_e((string) $chapter['id']) . '">';
        echo '<span>' . count($chapter['articles']) . '</span><strong>' . system_guide_e((string) $chapter['title']) . '</strong></a>';
    }
    echo '</section>';

    echo '<section class="course-layout">';
    echo '<aside class="course-toc" aria-label="Навигация по инструкции"><strong>На этой странице</strong><nav>';
    foreach ($chapters as $chapter) {
        echo '<a href="#guide-' . system_guide_e((string) $chapter['id']) . '">' . system_guide_e((string) $chapter['title']) . '</a>';
        foreach ($chapter['articles'] as $article) {
            echo '<a class="guide-toc-sub" href="#article-' . system_guide_e((string) $article['id']) . '">' . system_guide_e((string) $article['title']) . '</a>';
        }
    }
    echo '</nav></aside>';

    echo '<article class="course-reader">';
    echo '<section class="course-intro"><p class="eyebrow">Ваш доступ</p><h2>' . system_guide_e($role) . '</h2>';
    echo '<p class="course-text">Ниже только те процессы и кнопки, которые эта роль реально видит. Если администратор изменит матрицу прав, набор разделов пересчитается при следующем открытии страницы.</p></section>';

    foreach ($chapters as $chapter) {
        echo '<section class="course-lesson" id="guide-' . system_guide_e((string) $chapter['id']) . '">';
        echo '<div class="course-lesson__head"><span>Раздел</span><h2>' . system_guide_e((string) $chapter['title']) . '</h2>';
        echo '<p>' . system_guide_e((string) $chapter['summary']) . '</p></div>';
        echo '<div class="course-lesson__body">';
        foreach ($chapter['articles'] as $article) {
            echo '<article class="guide-article" id="article-' . system_guide_e((string) $article['id']) . '">';
            echo '<h3>' . system_guide_e((string) $article['title']) . '</h3>';
            foreach ($article['blocks'] as $block) {
                echo system_guide_render_block($block, $user);
            }
            echo '</article>';
        }
        echo '</div><a class="course-back-top" href="#top">К оглавлению</a></section>';
    }

    echo '</article></section>';
}
