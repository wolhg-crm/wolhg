/**
 * @return list<array<string,mixed>>
 */
function system_guide_visible_tree(array $user): array
{
    $chapters = [];
    foreach (system_guide_data()['chapters'] as $chapter) {
        if (!system_guide_user_matches($user, $chapter['see'] ?? [])) {
            continue;
        }
        $articles = [];
        foreach ($chapter['articles'] as $article) {
            if (!system_guide_user_matches($user, $article['see'] ?? [])) {
                continue;
            }
            $articles[] = $article;
        }
        if ($articles === []) {
            continue;
        }
        $chapter['articles'] = $articles;
        $chapters[] = $chapter;
    }

    return $chapters;
}

/**
 * @return list<string>
 */
function system_guide_article_ids(array $user): array
{
    $ids = [];
    foreach (system_guide_visible_tree($user) as $chapter) {
        foreach ($chapter['articles'] as $article) {
            $ids[] = (string) $article['id'];
        }
    }

    return $ids;
}

/**
 * @return list<string>
 */
function system_guide_all_article_ids(): array
{
    $ids = [];
    foreach (system_guide_data()['chapters'] as $chapter) {
        foreach ($chapter['articles'] as $article) {
            $ids[] = (string) $article['id'];
        }
    }

    return $ids;
}

function system_guide_visible_nav(array $user): array
{
    if (function_exists('app_sidebar_nav')) {
        return array_values(array_filter(
            app_sidebar_nav($user),
            static fn(array $item): bool => (bool) $item['visible']
        ));
    }

    $toHref = static function (string $path): string {
        return function_exists('app_path') ? app_path($path) : $path;
    };

    $role = (string) ($user['role'] ?? '');
    if ($role === 'member') {
        return [
            ['href' => $toHref('/'), 'label' => 'Главная'],
        ];
    }

    $items = [
        ['href' => $toHref('/'), 'label' => 'Главная'],
        ['href' => $toHref('/groups'), 'label' => 'Группы'],
        ['href' => $toHref('/care'), 'label' => 'Сопровождение'],
        ['href' => $toHref('/analytics'), 'label' => 'Аналитика'],
    ];
    if (system_guide_flag($user, 'manage_users')) {
        $items[] = ['href' => $toHref('/users'), 'label' => 'Люди'];
    }
    $items[] = ['href' => $toHref('/knowledge'), 'label' => 'Обучение'];
    if (system_guide_flag($user, 'settings_hub')) {
        $items[] = ['href' => $toHref('/settings'), 'label' => 'Настройки'];
    }

    return $items;
}

function system_guide_render_block(array $block, array $user): string
{
    $type = (string) ($block['type'] ?? 'p');
    if ($type === 'p') {
        return '<p class="course-text">' . system_guide_e((string) ($block['text'] ?? '')) . '</p>';
    }
    if ($type === 'callout') {
        return '<aside class="guide-callout"><strong>' . system_guide_e((string) ($block['title'] ?? ''))
            . '</strong><p>' . system_guide_e((string) ($block['text'] ?? '')) . '</p></aside>';
    }
    if ($type === 'list' || $type === 'steps') {
        $tag = $type === 'steps' ? 'ol' : 'ul';
        $html = '<' . $tag . ' class="guide-list">';
        foreach ($block['items'] ?? [] as $item) {
            $html .= '<li>' . system_guide_e((string) $item) . '</li>';
        }
        return $html . '</' . $tag . '>';
    }
    if ($type === 'ui') {
        $html = '<dl class="guide-ui">';
        foreach ($block['items'] ?? [] as $item) {
            $html .= '<div><dt>' . system_guide_e((string) ($item['name'] ?? ''))
                . '</dt><dd>' . system_guide_e((string) ($item['meaning'] ?? '')) . '</dd></div>';
        }
        return $html . '</dl>';
    }
    if ($type === 'legend') {
        $html = '<ul class="guide-legend">';
        foreach (system_guide_care_levels() as $level) {
            $html .= '<li><span class="dot ' . system_guide_e($level['level']) . '" aria-hidden="true"></span>'
                . '<div><strong>' . system_guide_e($level['label']) . '</strong>'
                . '<p>' . system_guide_e($level['rule']) . '</p></div></li>';
        }
        return $html . '</ul>';
    }
    if ($type === 'nav') {
        $html = '<ul class="guide-nav-preview">';
        foreach (system_guide_visible_nav($user) as $item) {
            $html .= '<li><code>' . system_guide_e((string) $item['href']) . '</code> — '
                . system_guide_e((string) $item['label']) . '</li>';
        }
        $html .= '<li><code>/profile</code> — Моя учетная запись</li>';
        return $html . '</ul>';
    }

    return '';
}

