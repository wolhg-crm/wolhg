/**
 * Role-scoped product guide for the Обучение section.
 * Visibility follows the same role/action/flag checks as the live UI.
 */

function system_guide_e(string $value): string
{
    if (function_exists('e')) {
        return e($value);
    }

    return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function system_guide_role_rank(string $role): int
{
    if (function_exists('role_rank')) {
        return role_rank($role);
    }

    return [
        'member' => 10,
        'assistant' => 20,
        'leader' => 30,
        'district_leader' => 40,
        'pastor' => 50,
        'admin' => 60,
        'super_admin' => 70,
    ][$role] ?? 0;
}

function system_guide_role_label(string $role): string
{
    return [
        'member' => 'Участник',
        'assistant' => 'Помощник лидера',
        'leader' => 'Лидер домашней группы',
        'district_leader' => 'Окружной лидер',
        'pastor' => 'Пастор',
        'admin' => 'Администратор',
        'super_admin' => 'Суперадминистратор',
    ][$role] ?? $role;
}

function system_guide_can_action(array $user, string $action): bool
{
    if (function_exists('can_action')) {
        try {
            return can_action($user, $action);
        } catch (Throwable) {
            // Fall through to defaults when the permission table is unavailable in tests.
        }
    }

    if (function_exists('default_permission')) {
        return default_permission((string) ($user['role'] ?? ''), $action);
    }

    $role = (string) ($user['role'] ?? '');
    if ($role === 'admin' || $role === 'super_admin') {
        return true;
    }
    if ($role === 'pastor') {
        return in_array($action, ['manage_security', 'edit_people', 'delete_people', 'manage_prayers', 'manage_services', 'view_church_analytics'], true);
    }
    if ($role === 'district_leader') {
        return in_array($action, ['edit_people', 'manage_prayers', 'manage_services', 'view_church_analytics'], true);
    }
    if (in_array($role, ['leader', 'assistant'], true)) {
        return in_array($action, ['edit_people', 'manage_prayers', 'manage_services'], true);
    }

    return false;
}

function system_guide_flag(array $user, string $flag): bool
{
    $role = (string) ($user['role'] ?? '');

    return match ($flag) {
        'manage_users' => function_exists('can_manage_users')
            ? can_manage_users($user)
            : in_array($role, ['leader', 'district_leader', 'pastor', 'admin', 'super_admin'], true),
        'create_home_group' => function_exists('can_create_home_group')
            ? can_create_home_group($user)
            : in_array($role, ['district_leader', 'pastor', 'admin', 'super_admin'], true),
        'assign_leader' => function_exists('can_assign_home_group_leader')
            ? can_assign_home_group_leader($user)
            : in_array($role, ['district_leader', 'pastor', 'admin', 'super_admin'], true),
        'manage_training' => function_exists('can_manage_training')
            ? can_manage_training($user)
            : in_array($role, ['district_leader', 'pastor', 'admin', 'super_admin'], true),
        'pwa_install' => function_exists('can_show_pwa_install')
            ? can_show_pwa_install($user)
            : system_guide_role_rank($role) >= system_guide_role_rank('leader'),
        'settings_hub' => function_exists('has_settings_hub_items')
            ? has_settings_hub_items($user)
            : system_guide_can_action($user, 'delete_people')
                || system_guide_can_action($user, 'manage_structure')
                || system_guide_can_action($user, 'manage_church_page')
                || $role === 'super_admin',
        'edit_group_data' => function_exists('can_edit_group_data')
            ? can_edit_group_data($user)
            : in_array($role, ['assistant', 'leader', 'district_leader', 'pastor', 'admin', 'super_admin'], true),
        'edit_group_info' => in_array($role, ['leader', 'district_leader', 'pastor', 'admin', 'super_admin'], true),
        'role_preview' => function_exists('can_use_role_preview_for_user')
            ? can_use_role_preview_for_user($user)
            : in_array($role, ['admin', 'super_admin'], true),
        'role_invites' => function_exists('role_invite_roles_for_user')
            ? role_invite_roles_for_user($user) !== []
            : in_array($role, ['leader', 'district_leader', 'pastor', 'admin', 'super_admin'], true),
        'approve_role_invites' => in_array($role, ['pastor', 'admin', 'super_admin'], true),
        'participant_requests' => function_exists('can_create_home_group')
            ? can_create_home_group($user)
            : in_array($role, ['district_leader', 'pastor', 'admin', 'super_admin'], true),
        'platform_admin' => $role === 'super_admin',
        'mcp_enabled' => function_exists('mcp_is_enabled') ? mcp_is_enabled() : false,
        default => false,
    };
}

/**
 * @param array{min_role?:string,roles?:list<string>,actions?:list<string>,flags?:list<string>} $rule
 */
function system_guide_user_matches(array $user, array $rule): bool
{
    $role = (string) ($user['role'] ?? '');
    if ($role === 'member') {
        return false;
    }

    if (isset($rule['min_role']) && system_guide_role_rank($role) < system_guide_role_rank((string) $rule['min_role'])) {
        return false;
    }

    if (isset($rule['roles']) && !in_array($role, $rule['roles'], true)) {
        return false;
    }

    foreach ($rule['actions'] ?? [] as $action) {
        if (!system_guide_can_action($user, (string) $action)) {
            return false;
        }
    }

    foreach ($rule['flags'] ?? [] as $flag) {
        if (!system_guide_flag($user, (string) $flag)) {
            return false;
        }
    }

    return true;
}

